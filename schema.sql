-- Production schema reference for QR Display App.
-- The live Supabase project has already been initialized.
-- If recreating the project elsewhere, replace <ADMIN_SETUP_SHA256>
-- with SHA-256 of a strong one-time admin setup code before running.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.qr_config (
  id bigint primary key,
  url text not null,
  title text not null default 'Quét mã QR để truy cập',
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create table if not exists public.qr_history (
  id bigint generated by default as identity primary key,
  url text not null,
  title text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

